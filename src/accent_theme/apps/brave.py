"""Sincroniza el tema y el color de acento de Brave con el acento de KDE.

Escribe en las preferencias de cada perfil:

- ``autogenerated.theme.color``: SkColor derivado del acento de KDE
- ``browser.theme.user_color``: SkColor (Material You de Chromium)
- ``browser.theme.color_scheme``: 2 (oscuro) o 1 (claro) según el modo de KDE
- ``browser.theme.color_variant``: 1 (TonalSpot)
- ``extensions.theme.use_system``: false, para forzar el color de acento

Y en ``Local State``:

- ``profile.info_cache.<perfil>.profile_color_seed``

El JSON se reescribe entero porque Brave no tiene un fichero aparte para
el tema: si Brave está abierto, el cambio entra al reiniciar el navegador.
"""

from __future__ import annotations

import configparser
import json
from pathlib import Path
from typing import TYPE_CHECKING

from accent_theme.apps.base import AppResult, accent_channels, atomic_write_json

if TYPE_CHECKING:
    from collections.abc import Mapping

KDEGLOBALS = Path.home() / ".config" / "kdeglobals"
DARK_LUMINANCE = 128
SKCOLOR_LIMIT = 0x80000000


def is_kde_dark(kdeglobals: Path = KDEGLOBALS) -> bool:
    """Detecta si el esquema de ventanas de KDE es oscuro o claro."""
    parser = configparser.ConfigParser(strict=False)
    parser.read(kdeglobals)
    try:
        red, green, blue = map(
            int,
            parser["Colors:Window"]["BackgroundNormal"].split(","),
        )
    except (KeyError, ValueError):
        return True
    luminance = 0.299 * red + 0.587 * green + 0.114 * blue
    return luminance < DARK_LUMINANCE


def rgb_to_skcolor(red: float, green: float, blue: float) -> int:
    """Convierte RGB (0.0-1.0) a SkColor signed de 32 bits (ARGB)."""
    channels = (
        round(red * 255),
        round(green * 255),
        round(blue * 255),
    )
    value = (0xFF << 24) | (channels[0] << 16) | (channels[1] << 8) | channels[2]
    if value >= SKCOLOR_LIMIT:
        value -= 0x100000000
    return value


def find_profiles(root: Path) -> list[Path]:
    """Encuentra las carpetas de perfiles dentro de una raíz de Brave."""
    profiles: list[Path] = []
    default = root / "Default"
    if default.is_dir():
        profiles.append(default)
    profiles.extend(sorted(path for path in root.glob("Profile *") if path.is_dir()))
    return profiles


def _update_local_state(path: Path, sk_color: int) -> bool:
    """Actualiza el ``profile_color_seed`` de cada perfil en Local State."""
    local = json.loads(path.read_text(encoding="utf-8"))
    info_cache = local.setdefault("profile", {}).setdefault("info_cache", {})
    changed = False
    for entry in info_cache.values():
        if entry.get("profile_color_seed") != sk_color:
            entry["profile_color_seed"] = sk_color
            changed = True
    if changed:
        atomic_write_json(path, local)
    return changed


def _update_preferences(path: Path, sk_color: int, color_scheme: int) -> None:
    """Fuerza el color de acento en las preferencias de un perfil."""
    preferences = json.loads(path.read_text(encoding="utf-8"))
    autogenerated = preferences.setdefault("autogenerated", {}).setdefault("theme", {})
    autogenerated["color"] = sk_color

    browser = preferences.setdefault("browser", {}).setdefault("theme", {})
    browser["user_color"] = sk_color
    browser["color_scheme"] = color_scheme
    browser["color_variant"] = 1

    extensions = preferences.setdefault("extensions", {}).setdefault("theme", {})
    extensions["use_system"] = False

    atomic_write_json(path, preferences)


def apply_brave(
    roots: tuple[Path, ...],
    accent: str,
    kdeglobals: Path = KDEGLOBALS,
) -> AppResult:
    """Aplica el acento de KDE a las preferencias de Brave."""
    existing = [root for root in roots if root.is_dir()]
    if not existing:
        return AppResult(app="brave", status="skipped", detail="sin instalación")

    try:
        red, green, blue = accent_channels(accent)
    except ValueError as error:
        return AppResult(app="brave", status="failed", detail=str(error))

    sk_color = rgb_to_skcolor(red, green, blue)
    color_scheme = 2 if is_kde_dark(kdeglobals) else 1
    updated = 0

    for root in existing:
        local_state = root / "Local State"
        if local_state.is_file():
            try:
                _update_local_state(local_state, sk_color)
            except (OSError, ValueError):
                continue

        for profile in find_profiles(root):
            preferences = profile / "Preferences"
            if not preferences.is_file():
                continue
            try:
                _update_preferences(preferences, sk_color, color_scheme)
            except (OSError, ValueError):
                continue
            updated += 1

    if updated == 0:
        return AppResult(app="brave", status="skipped", detail="sin perfiles")
    return AppResult(app="brave", status="applied", detail=f"{updated} perfiles")


def read_preferences(path: Path) -> Mapping[str, object]:
    """Lee las preferencias de un perfil (para las pruebas)."""
    return json.loads(path.read_text(encoding="utf-8"))
