#!/usr/bin/env python3
"""
Sincroniza el tema y color de acento de Brave Browser con el Accent de KDE.

Escribe en las preferencias de cada perfil de Brave:
  - autogenerated.theme.color: SkColor derivado del accent de KDE
  - browser.theme.user_color: SkColor (Material You / Chromium Color Provider)
  - browser.theme.color_scheme: 2 (Dark) o 1 (Light) según el modo de KDE
  - browser.theme.color_variant: 1 (TonalSpot)
  - extensions.theme.use_system: false (para forzar el color de acento)

Y en ~/.config/BraveSoftware/Brave-Browser/Local State:
  - profile.info_cache.<perfil>.profile_color_seed

Nota: Escritura atómica para evitar corrupción de archivos. Si Brave está
abierto al cambiar de color, el cambio se aplica al reiniciar el navegador o
al abrir una nueva ventana.
"""
import colorsys
import configparser
import glob
import json
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from bridge import get_accent_rgb, hsv_to_hex

KDEGLOBALS = os.path.expanduser("~/.config/kdeglobals")


def is_kde_dark():
    """Detecta si el esquema de ventanas de KDE es oscuro o claro."""
    cfg = configparser.ConfigParser(strict=False)
    cfg.read(KDEGLOBALS)
    try:
        r, g, b = map(int, cfg["Colors:Window"]["BackgroundNormal"].split(","))
        luminance = 0.299 * r + 0.587 * g + 0.114 * b
        return luminance < 128
    except Exception:
        return True


def rgb_to_skcolor(r_float, g_float, b_float):
    """Convierte RGB (0.0 - 1.0) a SkColor signed 32-bit int (ARGB)."""
    r = int(round(r_float * 255))
    g = int(round(g_float * 255))
    b = int(round(b_float * 255))
    val = (0xFF << 24) | (r << 16) | (g << 8) | b
    if val >= 0x80000000:
        val -= 0x100000000
    return val


def find_brave_roots():
    """Encuentra las carpetas raíz de Brave (nativa y flatpak si existiera)."""
    roots = [
        os.path.expanduser("~/.config/BraveSoftware/Brave-Browser"),
        os.path.expanduser("~/.var/app/com.brave.Browser/config/BraveSoftware/Brave-Browser"),
    ]
    return [d for d in roots if os.path.isdir(d)]


def find_profiles(root):
    """Encuentra todas las carpetas de perfiles dentro de una raíz de Brave."""
    profiles = []
    default_dir = os.path.join(root, "Default")
    if os.path.isdir(default_dir):
        profiles.append(default_dir)
    for p in glob.glob(os.path.join(root, "Profile *")):
        if os.path.isdir(p):
            profiles.append(p)
    return profiles


def save_json_atomic(filepath, data):
    """Guarda un JSON de forma atómica usando un archivo temporal."""
    dirname = os.path.dirname(filepath)
    tmp_fd, tmp_path = tempfile.mkstemp(dir=dirname, suffix=".tmp")
    try:
        with os.fdopen(tmp_fd, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)
            f.write("\n")
        os.replace(tmp_path, filepath)
        return True
    except OSError as e:
        try:
            os.unlink(tmp_path)
        except OSError:
            pass
        print(f"Brave: error al guardar {filepath}: {e}")
        return False


def main():
    roots = find_brave_roots()
    if not roots:
        print("No se encontró instalación de Brave Browser.")
        return

    _mh = os.environ.get("MATUGEN_ACCENT", "").lstrip("#")
    if len(_mh) == 6:
        try:
            r, g, b = (int(_mh[i:i + 2], 16) / 255 for i in (0, 2, 4))
        except ValueError:
            r, g, b = get_accent_rgb()
    else:
        r, g, b = get_accent_rgb()
    h, s, v = colorsys.rgb_to_hsv(r, g, b)
    accent_hex = hsv_to_hex(h, s, v)
    sk_color = rgb_to_skcolor(r, g, b)
    color_scheme = 2 if is_kde_dark() else 1

    total_profiles = 0

    for root in roots:
        # 1. Actualizar Local State si existe
        local_state_path = os.path.join(root, "Local State")
        if os.path.isfile(local_state_path):
            try:
                with open(local_state_path, "r", encoding="utf-8") as f:
                    local_data = json.load(f)
                info_cache = local_data.setdefault("profile", {}).setdefault("info_cache", {})
                changed_local = False
                for profile_name in list(info_cache.keys()):
                    p_entry = info_cache[profile_name]
                    if p_entry.get("profile_color_seed") != sk_color:
                        p_entry["profile_color_seed"] = sk_color
                        changed_local = True
                if changed_local:
                    save_json_atomic(local_state_path, local_data)
            except Exception as e:
                print(f"Brave: aviso en Local State: {e}")

        # 2. Actualizar Preferences en cada perfil
        profiles = find_profiles(root)
        for profile_dir in profiles:
            p_name = os.path.basename(profile_dir)
            pref_path = os.path.join(profile_dir, "Preferences")
            if not os.path.isfile(pref_path):
                continue

            try:
                with open(pref_path, "r", encoding="utf-8") as f:
                    pref_data = json.load(f)

                # autogenerated.theme.color
                auto_theme = pref_data.setdefault("autogenerated", {}).setdefault("theme", {})
                auto_theme["color"] = sk_color

                # browser.theme
                b_theme = pref_data.setdefault("browser", {}).setdefault("theme", {})
                b_theme["user_color"] = sk_color
                b_theme["color_scheme"] = color_scheme
                b_theme["color_variant"] = 1

                # extensions.theme
                ext_theme = pref_data.setdefault("extensions", {}).setdefault("theme", {})
                ext_theme["use_system"] = False

                if save_json_atomic(pref_path, pref_data):
                    print(f"Brave [{p_name}]: accent {accent_hex} (SkColor {sk_color}) aplicado.")
                    total_profiles += 1
            except Exception as e:
                print(f"Brave [{p_name}]: error al procesar preferencias: {e}")

    if total_profiles == 0:
        print("No se encontraron perfiles de Brave para actualizar.")


if __name__ == "__main__":
    main()
